    r"|sed\s+(?:-[a-z]*i\S*\s+(?:-\S+\s+)*\S+|(?:-\S+\s+)*[\"']?s/[^/\n]*/[^/\n]*/)"
    r"|(?:ba|z|k)?sh\s+(?:-\S+\s+)*[\w./~$-]+\.sh\b"
    r"|mv\s+(?:-[a-z]+\s+)*[\w./~$*-]+\s+[\w./~$*-]+"
