    r"alias\s+[\w.-]+=\S*"
    r"|(?:rg|ripgrep)\s+[-\w'\"./*]+"
    r"|curl\s+(?:-\S+\s+)*\S+"
    r"|wget\s+(?:-\S+\s+)*\S+"
    r"|rm\s+(?:-[a-z]+\s+)*[\w./~*$-]+"
    r"|echo\s+[^\n>]*>>?\s*\S+"
    r"|dd\s+(?:if|of)=\S+"
    r"|git\s+(?:clone|push|pull|fetch|reset|checkout|remote|config|rm|apply|am)\b[^\n]*"
    r"|tar\s+-?[a-z]*[xcz][a-z]*f?\s+\S+"
    r"|chmod\s+(?:-[a-z]+\s+)*[0-7ugoa+=,rwxst-]+\s+\S+"
    r"|chown\s+(?:-[a-z]+\s+)*[\w.:-]+\s+\S+"
    r"|fsck(?:\.\w+)?(?:\s+-\S+)*\s+\S+"
    r"|mkfs(?:\.\w+)?\s+\S+"
    r"|shred\s+(?:-\S+\s+)*\S+"
